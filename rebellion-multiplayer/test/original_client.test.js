import test from 'node:test';
import assert from 'node:assert/strict';
import { makeEngine, makeConn, X } from './helpers.js';
import { DEFAULTS } from '../src/engine.js';

// Exactly what the original frame_13 does: es.login(username, "", {token: ...}) and es.createRoom({... zone "HW Chat"})
const ORIGINAL_LOGIN = (n) => `<XmlDoc><Action>Login</Action><Parameters><Name>${n}</Name><Password></Password><EventHandlerVariables><EventHandlerVariable><Name>token</Name><Data>k4bj9OVWBHCKKqoOJQLLl8uZSXGwDY0o1NByp5W5T1w=</Data></EventHandlerVariable></EventHandlerVariables></Parameters></XmlDoc>`;
const CREATE_LOBBY = '<XmlDoc><Action>CreateRoom</Action><Parameters><Zone><Name>HW Chat</Name></Zone><Room><Name>Lobby42</Name><Password></Password><Numbered>true</Numbered><Capacity>0</Capacity></Room></Parameters></XmlDoc>';

function boot(engine, nick) {
  const c = makeConn(nick); engine.connect(c);
  engine.receive(c, ORIGINAL_LOGIN(nick));               // login carries a token variable; the name must still parse correctly
  engine.receive(c, CREATE_LOBBY);                        // loggedIn -> joinLobby()
  engine.receive(c, X.raw('RebellionRace'));
  return c;
}

test('original login (with token variable) is accepted and the lobby CreateRoom gets Success', () => {
  const { engine } = makeEngine();
  const c = boot(engine, 'Ann');
  assert.match(c.sent[1], /<Action>LoginResponse<\/Action>.*<Result>Accepted<\/Result><Username>Ann<\/Username>/);
  assert.equal(c.sent[2], '<XmlDoc><Action>CreateRoom</Action><Parameters><Result>Success</Result></Parameters></XmlDoc>');
});

test('CreateRoom before login is refused', () => {
  const { engine } = makeEngine();
  const c = makeConn('Ann'); engine.connect(c);
  engine.receive(c, CREATE_LOBBY);
  assert.match(c.sent[1], /<Action>CreateRoom<\/Action>.*<Result>Failure<\/Result>/);
});

test('leaving a race = joinLobby() = CreateRoom: seat is freed and opponents get UL', () => {
  const { engine, clock } = makeEngine();
  const a = boot(engine, 'Ann'); const b = boot(engine, 'Bob');
  engine.receive(a, X.join()); engine.receive(b, X.join());
  clock.advance(DEFAULTS.openGraceMs); engine.receive(a, 'R'); engine.receive(b, 'R');
  assert.ok(a.last('PGCD'));
  engine.receive(b, CREATE_LOBBY);                         // Bob walks back to the garage
  assert.equal(a.last('UL'), 'UL|Bob');
  assert.ok(a.codes().includes('PGCDC'));                  // countdown cancelled, Ann waits
  assert.equal(engine.stats().rooms[0].players, 1);
});

test('a guest name generated by the SWF (remoting failed) is declined, not adopted', () => {
  const { engine } = makeEngine();
  const c = makeConn('Ann'); engine.connect(c);
  engine.receive(c, ORIGINAL_LOGIN('DesertDog_209'));
  assert.match(c.sent[1], /<Result>Declined<\/Result>/);
});
